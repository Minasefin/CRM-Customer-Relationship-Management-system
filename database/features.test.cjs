const {test}=require('node:test');
const assert=require('node:assert/strict');
const fs=require('node:fs');
const os=require('node:os');
const path=require('node:path');
const {randomBytes}=require('node:crypto');
const SQLite=require('better-sqlite3-multiple-ciphers');
const {createDatabase}=require('./index.cjs');
const {createAuth}=require('../auth/index.cjs');
const {resolveStorage,relocateStorage}=require('./storage.cjs');
const {MAX_ATTACHMENT_BYTES}=require('./attachments.cjs');
function fixture(t) {
 const root=fs.mkdtempSync(path.join(os.tmpdir(),'crm-features-'));
 t.after(()=>fs.rmSync(root,{recursive:true,force:true}));
 return root;
}
test('v1 encrypted migration preserves relationships and optional names survive restart',async t=>{
 const root=fixture(t),file=path.join(root,'crm.db'),key=randomBytes(32);
 const old=new SQLite(file);old.key(key);
 old.exec(fs.readFileSync(path.join(__dirname,'migrations','001-original.sql'),'utf8'));
 old.prepare("INSERT INTO organizations VALUES (?,?,?,?,?,?,?)").run('o','Synthetic legacy firm','','',null,0,new Date().toISOString());
 old.prepare("INSERT INTO contacts VALUES (?,?,?,?,?,?,?,?,?,?)").run('c','o','Synthetic','Legacy','','active','','',null,new Date().toISOString());
 old.close();
 const db=createDatabase(file); t.after(()=>db.closeDatabase());db.openDatabase(key);
 assert.equal((await db.getContact('c')).middleName,'');
 const updated=await db.updateContact('c',{middleName:'Test',prefix:'Dr.',suffix:'III'});
 assert.equal(updated.orgId,'o');assert.equal(updated.middleName,'Test');
 await db.updateContact('c',{title:'Updated'});
 assert.equal((await db.getContact('c')).prefix,'Dr.');
 await assert.rejects(db.updateContact('c',{suffix:'x'.repeat(51)}));
 db.closeDatabase();db.openDatabase(key);
 assert.equal((await db.getContact('c')).suffix,'III');
 db.closeDatabase();
 const raw=new SQLite(file);raw.key(key);assert.equal(raw.pragma('user_version',{simple:true}),2);raw.close();
});
test('attachments are encrypted, bounded, archived, restored and retained after rekey',async t=>{
 const root=fixture(t),file=path.join(root,'crm.db'),key=randomBytes(32),next=randomBytes(32);
 const db=createDatabase(file);t.after(()=>db.closeDatabase());db.openDatabase(key);
 const org=await db.createOrganization({name:'Synthetic attachments'});
 const body=Buffer.from('%PDF-1.7 Synthetic unique attachment payload 7492');
 const input={name:'example.pdf',mimeType:'application/pdf',dataBase64:body.toString('base64')};
 const a=await db.addOrganizationAttachment(org.id,input);
 assert.equal(a.size,body.length);assert.equal(a.dataBase64,undefined);
 assert.deepEqual(Buffer.from((await db.getOrganizationAttachment(a.id)).dataBase64,'base64'),body);
 for(const change of [{name:'../bad.pdf'},{name:'run.exe'},{mimeType:'text/html'},{dataBase64:'%%%%'},{dataBase64:''},{dataBase64:Buffer.alloc(MAX_ATTACHMENT_BYTES+1).toString('base64')}]) await assert.rejects(db.addOrganizationAttachment(org.id,{...input,...change}));
 await assert.rejects(db.addOrganizationAttachment('missing',input));
 const boundary=await db.addOrganizationAttachment(org.id,{name:'limit.txt',mimeType:'text/plain',dataBase64:Buffer.alloc(MAX_ATTACHMENT_BYTES,65).toString('base64')});
 assert.equal(boundary.size,MAX_ATTACHMENT_BYTES);
 await db.archiveOrganizationAttachment(a.id,true);
 assert.equal((await db.getOrganizationAttachments(org.id))[0].archived,true);
 await db.archiveOrganization(org.id,true);
 await assert.rejects(db.addOrganizationAttachment(org.id,input));
 await db.archiveOrganizationAttachment(a.id,false);
 db.rekeyDatabase(next);db.closeDatabase();
 assert.equal(fs.readFileSync(file).includes(body),false);
 assert.throws(()=>db.openDatabase(key));
 db.openDatabase(next);
 assert.equal((await db.getOrganizationAttachment(a.id)).dataBase64,input.dataBase64);
 db.closeDatabase();await assert.rejects(db.getOrganizationAttachments(org.id));
});
test('storage relocation retains paired files and login works from new location',async t=>{
 const root=fixture(t), source=path.join(root,'source'),target=path.join(root,'target');
 fs.mkdirSync(source);fs.mkdirSync(target);
 const db=createDatabase(path.join(source,'crm.db'));t.after(()=>db.closeDatabase());
 const auth=createAuth({database:db,directory:source});
 const password='Synthetic relocation '+randomBytes(16).toString('hex');
 await auth.setUpPassword(password);
 const org=await db.createOrganization({name:'Synthetic relocation firm'});
 await db.addOrganizationAttachment(org.id,{name:'note.txt',mimeType:'text/plain',dataBase64:Buffer.from('Synthetic relocation bytes').toString('base64')});
 db.prepareRelocation();auth.lock();
 const result=relocateStorage(source,source,target);
 assert.equal(result.restartRequired,true);assert.equal(resolveStorage(source),target);
 for(const name of ['crm.db','auth.json']) assert.deepEqual(fs.readFileSync(path.join(source,name)),fs.readFileSync(path.join(target,name)));
 const moved=createDatabase(path.join(target,'crm.db'));t.after(()=>moved.closeDatabase());
 const nextAuth=createAuth({database:moved,directory:target});
 assert.equal((await nextAuth.login(password)).ok,true);
 assert.equal((await moved.getOrganizations())[0].id,org.id);
 assert.equal((await moved.getOrganizationAttachments(org.id)).length,1);
 nextAuth.lock();
 fs.renameSync(target,target+'-offline');
 assert.throws(()=>resolveStorage(source),/unavailable/);
 assert.equal(fs.existsSync(target),false);
});
test('relocation rejects nonempty targets, missing pairs, sidecars and pointer failures without losing originals',t=>{
 const root=fixture(t),source=path.join(root,'source'),target=path.join(root,'target'),config=path.join(root,'config');
 fs.mkdirSync(source);fs.mkdirSync(target);fs.mkdirSync(config);
 fs.writeFileSync(path.join(source,'crm.db'),'synthetic encrypted stand-in');
 assert.throws(()=>relocateStorage(config,source,target),/Both/);
 fs.writeFileSync(path.join(source,'auth.json'),'synthetic metadata');
 fs.writeFileSync(path.join(target,'keep.txt'),'preserve');
 assert.throws(()=>relocateStorage(config,source,target),/empty/);
 assert.equal(fs.readFileSync(path.join(target,'keep.txt'),'utf8'),'preserve');
 fs.unlinkSync(path.join(target,'keep.txt'));
 fs.writeFileSync(path.join(source,'crm.db-wal'),'pending');
 assert.throws(()=>relocateStorage(config,source,target),/in use/);
 fs.unlinkSync(path.join(source,'crm.db-wal'));
 fs.mkdirSync(path.join(config,'storage-location.json'));
 assert.throws(()=>relocateStorage(config,source,target),/Could not move/);
 assert.deepEqual(fs.readdirSync(target),[]);
 assert.equal(fs.readFileSync(path.join(source,'crm.db'),'utf8'),'synthetic encrypted stand-in');
});
