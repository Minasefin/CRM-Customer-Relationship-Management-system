'use strict';
// Optional integration suite: runs when Nic's TOTP implementation is present.
const {test}=require('node:test');
const assert=require('node:assert/strict');
const fs=require('node:fs');
const os=require('node:os');
const path=require('node:path');
const {randomBytes,createHmac}=require('node:crypto');
const {createDatabase}=require('./index.cjs');
const {createAuth}=require('../auth/index.cjs');
const {relocateStorage,resolveStorage}=require('./storage.cjs');
const available=typeof createAuth({directory:os.tmpdir(),database:{}}).loginWithTotp==='function';
function code(secret,time) {
 const bits=[...secret].map(c=>'ABCDEFGHIJKLMNOPQRSTUVWXYZ234567'.indexOf(c).toString(2).padStart(5,'0')).join('');
 const key=Buffer.from(bits.match(/.{8}/g).map(x=>parseInt(x,2)));
 const counter=Buffer.alloc(8);counter.writeBigUInt64BE(BigInt(Math.floor(time/30000)));
 const digest=createHmac('sha1',key).update(counter).digest();key.fill(0);
 return String((digest.readUInt32BE(digest[digest.length-1]&15)&0x7fffffff)%1000000).padStart(6,'0');
}
test('TOTP/recovery state survives names, attachments, rekey and paired relocation',{skip:!available},async t=>{
 const root=fs.mkdtempSync(path.join(os.tmpdir(),'crm-totp-db-'));
 t.after(()=>fs.rmSync(root,{recursive:true,force:true}));
 const source=path.join(root,'source'),target=path.join(root,'target');fs.mkdirSync(source);fs.mkdirSync(target);
 const db=createDatabase(path.join(source,'crm.db'));t.after(()=>db.closeDatabase());
 let time=1800000000000;
 const options={database:db,directory:source,now:()=>time,monotonicNow:()=>time};
 const auth=createAuth(options),password='Synthetic integration '+randomBytes(16).toString('hex'),next='Synthetic replacement '+randomBytes(16).toString('hex');
 await auth.setUpPassword(password);
 const org=await db.createOrganization({name:'Synthetic TOTP firm'});
 const c=await db.createContact({firstName:'Synthetic',middleName:'Middle',lastName:'Person',prefix:'Dr.',suffix:'III',orgId:org.id});
 const content=Buffer.from('Synthetic encrypted attachment with TOTP');
 const a=await db.addOrganizationAttachment(org.id,{name:'sample.txt',mimeType:'text/plain',dataBase64:content.toString('base64')});
 const enrollment=await auth.beginTotpSetup(password);assert.equal(enrollment.ok,true);
 const confirmed=await auth.confirmTotpSetup(code(enrollment.secret,time));assert.equal(confirmed.ok,true);
 auth.lock();
 assert.equal((await auth.login(password)).ok,false);
 await assert.rejects(db.getOrganizationAttachment(a.id),/locked/);
 time+=61000;
 assert.equal((await auth.loginWithTotp(password,confirmed.recoveryCodes[0])).ok,true);
 assert.equal((await auth.changePassword(password,next)).ok,true);
 db.prepareRelocation();auth.lock();
 const before=fs.readFileSync(path.join(source,'auth.json'));
 relocateStorage(source,source,target);
 assert.deepEqual(fs.readFileSync(path.join(target,'auth.json')),before);
 assert.equal(resolveStorage(source),target);
 const moved=createDatabase(path.join(target,'crm.db'));t.after(()=>moved.closeDatabase());
 const restarted=createAuth({database:moved,directory:target,now:()=>time,monotonicNow:()=>time});
 assert.deepEqual(await restarted.getTotpStatus(),{enabled:true});
 assert.equal((await restarted.loginWithTotp(password,confirmed.recoveryCodes[1])).ok,false);
 time+=61000;
 assert.equal((await restarted.login(next)).ok,false);
 time+=61000;
 assert.equal((await restarted.loginWithTotp(next,confirmed.recoveryCodes[0])).ok,false);
 time+=61000;
 const fresh=code(enrollment.secret,time);
 assert.equal((await restarted.loginWithTotp(next,fresh)).ok,true);
 assert.equal((await moved.getContact(c.id)).middleName,'Middle');
 assert.equal((await moved.getContact(c.id)).prefix,'Dr.');
 assert.equal((await moved.getOrganizationAttachment(a.id)).dataBase64,content.toString('base64'));
 restarted.lock();
 assert.equal((await restarted.loginWithTotp(next,fresh)).ok,false);
 time+=61000;
 assert.equal((await restarted.loginWithTotp(next,confirmed.recoveryCodes[1])).ok,true);
 restarted.lock();
 const again=createAuth({database:moved,directory:target,now:()=>time,monotonicNow:()=>time});
 assert.equal((await again.loginWithTotp(next,confirmed.recoveryCodes[1])).ok,false);
 assert.equal(fs.readFileSync(path.join(target,'crm.db')).includes(content),false);
});
